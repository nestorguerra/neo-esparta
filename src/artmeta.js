function applyArtMeta(def) {
  const m = ARTMETA[def.id];
  if (!m || typeof ART === 'undefined' || !ART[def.id]) return;
  if (m.focus) def.focus = m.focus;
  if (m.ta) def.ta = m.ta;
  if (m.relief) def.relief = m.relief;
  (m.bub || []).forEach((p, i) => { const b = def.bub && def.bub[i]; if (!b) return; b[2] = p[0]; b[3] = p[1]; if (p[2]) b[4] = Object.assign({}, b[4], { w: p[2] }); });
  (m.sfx || []).forEach((p, i) => { const s = def.sfx && def.sfx[i]; if (!s) return; s[1] = p[0]; s[2] = p[1]; });
}
